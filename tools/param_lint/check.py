"""param_lint: checks calls to procs marked with SHOULD_CALL_ALL_PARAMS /
SHOULD_STATE_PARAM_NAMES / SHOULD_KEEP_PARAM_ORDER. See tools/param_lint/README.md.

Usage (from the repository root):
	tools/bootstrap/python -m param_lint.check [path/to/environment.dme]
"""

import argparse
import os
import sys
import tempfile
import time

from .analysis import RULES, Analyzer, Diagnostic
from .source import SourceFile, collect_defines, collect_included_files, find_markers

# avulto 0.1.x panics on these builtin macros (expr_parse.rs `todo!()`), which
# would make every proc using stack_trace() unwalkable. Replacing them with a
# single `null` token keeps the argument count of every call unchanged.
WRAPPER_DEFINES = (
	("__TYPE__", "null"),
	("__IMPLIED_TYPE__", "null"),
)


class Options:
	def __init__(self, check_defaults=True):
		self.check_defaults = check_defaults


class SourceCache:
	def __init__(self):
		self._files = {}

	def get(self, path):
		key = os.path.normcase(os.path.abspath(path))
		src = self._files.get(key)
		if src is None:
			src = self._files[key] = SourceFile(os.path.abspath(path))
		return src

	def values(self):
		return self._files.values()


class Result:
	def __init__(self):
		self.diagnostics = []
		self.passes = 0
		self.procs = 0
		self.walked = 0
		self.marked = 0
		self.checked_calls = 0
		self.elapsed = 0.0


def _parse_define(text):
	name, sep, value = text.partition("=")
	name = name.strip()
	if not name.isidentifier():
		raise ValueError(f"invalid define name {name!r}")
	return name, value.strip() if sep else ""


def write_wrapper(directory, dme_path, defines):
	path = os.path.join(directory, "param_lint_wrapper.dme")
	lines = ["// Generated by tools/param_lint; safe to delete."]
	for name, value in list(WRAPPER_DEFINES) + list(defines):
		lines.append(f"#define {name} {value}".rstrip())
	lines.append('#include "' + os.path.abspath(dme_path).replace("\\", "/") + '"')
	with open(path, "w", encoding="utf-8", newline="\n") as f:
		f.write("\n".join(lines) + "\n")
	return path


def run(dme_path, defines=(), extra_passes=(), options=None):
	"""Run all passes over `dme_path`; returns a Result."""
	from avulto import DME  # imported lazily so --help works without avulto

	options = options or Options()
	start = time.monotonic()
	result = Result()
	dme_path = os.path.abspath(dme_path)
	if not os.path.isfile(dme_path):
		raise FileNotFoundError(dme_path)

	sources = SourceCache()
	files = collect_included_files(dme_path)
	for f in files:
		sources.get(f)
	macros = collect_defines(s.text for s in list(sources.values()))

	diags = []
	should_hits = []
	skip_hits = []
	for f in files:
		for hit in find_markers(sources.get(f)):
			if hit.error:
				diags.append(Diagnostic(hit.file, hit.line, "bad_marker", hit.error))
			elif hit.kind == "PARAM_LINT_SKIP":
				skip_hits.append(hit)
			elif hit.arg.strip() not in ("TRUE", "FALSE", "1", "0"):
				diags.append(Diagnostic(hit.file, hit.line, "bad_marker", f"`{hit.kind}({hit.arg})`: the argument must be TRUE, FALSE, 1 or 0"))
			else:
				should_hits.append(hit)

	passes = [list(defines)]
	for extra in extra_passes:
		passes.append(list(defines) + list(extra))

	mapped = set()
	used_skips = set()
	for pass_defines in passes:
		with tempfile.TemporaryDirectory(prefix="param_lint_") as tmp:
			wrapper = write_wrapper(tmp, dme_path, pass_defines)
			dme = DME.from_file(wrapper, parse_procs=True)
			an = Analyzer(dme, tmp, sources, macros, options)
			an.map_markers(should_hits, mapped)
			an.setup_skips(skip_hits, used_skips)
			an.run()
			diags.extend(an.diags)
			result.passes += 1
			result.procs = max(result.procs, len(an.all_procs))
			result.walked = max(result.walked, an.walked)
			result.checked_calls = max(result.checked_calls, an.checked_calls)
			result.marked = max(result.marked, sum(1 for pi in an.all_procs if any(an.eff_def(pi))))
			del an, dme

	for hit in should_hits:
		if id(hit) not in mapped:
			diags.append(Diagnostic(hit.file, hit.line, "bad_marker", f"`{hit.kind}` is not inside the body of any proc definition"))
	for hit in skip_hits:
		if id(hit) not in used_skips:
			diags.append(Diagnostic(hit.file, hit.line, "unused_skip", "PARAM_LINT_SKIP() does not wrap a call that would have produced a param_lint error; remove it"))

	seen = set()
	unique = []
	for d in diags:
		k = d.key()
		if k not in seen:
			seen.add(k)
			unique.append(d)
	unique.sort(key=lambda d: (os.path.normcase(d.path), d.line, d.rule, d.message))
	result.diagnostics = unique
	result.elapsed = time.monotonic() - start
	return result


def display_path(path):
	try:
		rel = os.path.relpath(path)
	except ValueError:
		return path.replace("\\", "/")
	if rel.startswith(".."):
		return path.replace("\\", "/")
	return rel.replace("\\", "/")


def _gh_escape(text, prop=False):
	text = text.replace("%", "%25").replace("\r", "%0D").replace("\n", "%0A")
	if prop:
		text = text.replace(":", "%3A").replace(",", "%2C")
	return text


def main(argv=None):
	parser = argparse.ArgumentParser(prog="param_lint", description="Check calls to procs marked with SHOULD_CALL_ALL_PARAMS / SHOULD_STATE_PARAM_NAMES / SHOULD_KEEP_PARAM_ORDER.")
	parser.add_argument("dme", nargs="?", default="beestation.dme", help="environment to check (default: beestation.dme)")
	parser.add_argument("-D", "--define", action="append", default=[], metavar="NAME[=VALUE]", help="add a preprocessor define to every pass")
	parser.add_argument("--extra-pass", action="append", default=[], metavar="NAME[=VALUE],...", help="also run a pass with these extra defines (comma separated); results are merged")
	parser.add_argument("--no-default-value-check", action="store_true", help="do not report default values on SHOULD_CALL_ALL_PARAMS procs (rule default_value)")
	parser.add_argument("--exit-zero", action="store_true", help="exit with 0 even when errors are reported (for editor tasks that must not stop a following build)")
	parser.add_argument("--list-rules", action="store_true", help="print the rule ids and exit")
	args = parser.parse_args(argv)

	if args.list_rules:
		for rule, desc in RULES.items():
			print(f"{rule}: {desc}")
		return 0

	try:
		defines = [_parse_define(d) for d in args.define]
		extra = [[_parse_define(d) for d in group.split(",") if d.strip()] for group in args.extra_pass]
	except ValueError as exc:
		parser.error(str(exc))

	sys.setrecursionlimit(max(sys.getrecursionlimit(), 20000))
	result = run(args.dme, defines, extra, Options(check_defaults=not args.no_default_value_check))

	on_github = os.getenv("GITHUB_ACTIONS") == "true"
	counts = {}
	for d in result.diagnostics:
		counts[d.rule] = counts.get(d.rule, 0) + 1
		path = display_path(d.path)
		print(f"{path}:{d.line}: error[{d.rule}]: {d.message}")
		if on_github:
			print(f"::error file={_gh_escape(path, True)},line={d.line},title={_gh_escape('param_lint ' + d.rule, True)}::{_gh_escape(d.message)}")

	total = len(result.diagnostics)
	breakdown = ", ".join(f"{k}: {v}" for k, v in sorted(counts.items()))
	print(
		f"param_lint: {total} error(s){' (' + breakdown + ')' if breakdown else ''}; "
		f"{result.passes} pass(es), {result.walked}/{result.procs} procs walked, "
		f"{result.marked} marked definition(s), {result.checked_calls} call(s) to marked procs checked; {result.elapsed:.1f}s"
	)
	return 1 if total and not args.exit_zero else 0


if __name__ == "__main__":
	sys.exit(main())
